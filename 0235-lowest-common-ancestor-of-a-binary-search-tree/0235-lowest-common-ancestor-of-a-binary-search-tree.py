# Definition for a binary tree node.
# class TreeNode(object):
#     def __init__(self, x):
#         self.val = x
#         self.left = None
#         self.right = None

class Solution(object):
    def lowestCommonAncestor(self, root, p, q):
        """
        :type root: TreeNode
        :type p: TreeNode
        :type q: TreeNode
        :rtype: TreeNode
        """
        temp=root
        while True:
            if p.val<temp.val and q.val<temp.val:
                temp=temp.left
            elif p.val>temp.val and q.val>temp.val:
                temp=temp.right
            elif p==temp or q==temp:
                return temp
            else:
                return temp
        

